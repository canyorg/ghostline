//! UI strings in English, Turkish and Russian.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Tr,
    Ru,
}

impl Lang {
    pub const ALL: [Lang; 3] = [Lang::En, Lang::Tr, Lang::Ru];

    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "EN",
            Lang::Tr => "TR",
            Lang::Ru => "RU",
        }
    }

    /// Pick from LANG / LC_ALL / LANGUAGE, default English.
    pub fn detect() -> Lang {
        for var in ["GHOSTLINE_LANG", "LC_ALL", "LANGUAGE", "LANG"] {
            if let Ok(v) = std::env::var(var) {
                let v = v.to_ascii_lowercase();
                if v.starts_with("tr") {
                    return Lang::Tr;
                }
                if v.starts_with("ru") {
                    return Lang::Ru;
                }
                if !v.is_empty() && v != "c" && v != "posix" {
                    return Lang::En;
                }
            }
        }
        Lang::En
    }

    pub fn t(self) -> &'static T {
        match self {
            Lang::En => &EN,
            Lang::Tr => &TR,
            Lang::Ru => &RU,
        }
    }
}

